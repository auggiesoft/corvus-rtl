#!/usr/bin/env bash
# Build corvus-rtl in Docker:  build/build.sh [version]   -> out/
#   corvus-rtl-<v>-windows-x64.dll      librtlsdr with libusb inside (imports only KERNEL32 and msvcrt)
#   corvus-rtl-driver-<v>-windows-x64.exe  the WinUSB installer (asks for administrator rights)
#   libcorvus-rtl-<v>-linux-x86_64.so   librtlsdr against the system's libusb-1.0
#   SHA256SUMS
set -euo pipefail
R=$(cd "$(dirname "$0")/.." && pwd)
V=${1:-$(git -C "$R" describe --tags --always --dirty)}
DV=$(echo "${V#v}" | grep -E '^[0-9]+\.[0-9]+\.[0-9]+$' >/dev/null && echo "${V#v}.0" || echo 0.0.0.0)
image() { docker image inspect "corvus-rtl-$1" >/dev/null 2>&1 || docker build --progress=plain -t "corvus-rtl-$1" -f "$R/build/Dockerfile.$1" "$R/build" >/dev/null; }
run() { docker run --rm -u "$(id -u):$(id -g)" -v "$R":/src -w /src "corvus-rtl-$1" bash -ec "$2"; }
image mingw
image linux
case "$R/out" in "$R"/out) rm -rf "$R/out" ;; esac
mkdir -p "$R/out"
# the dongles librtlsdr knows, for the driver's INF
{
  echo "/* generated by build/build.sh from rtl-sdr/src/librtlsdr.c (known_devices) */"
  echo "static const struct { unsigned vid, pid; const char *name; } RTL_IDS[] = {"
  awk '/static rtlsdr_dongle_t known_devices/,/^};/' "$R/rtl-sdr/src/librtlsdr.c" \
    | grep -oE '0x[0-9a-fA-F]{4}, 0x[0-9a-fA-F]{4}, "[^"]*"' | sed 's/^/\t{ /; s/$/ },/'
  echo "};"
} > "$R/driver/ids.h"
SRC='rtl-sdr/src/librtlsdr.c rtl-sdr/src/tuner_e4k.c rtl-sdr/src/tuner_fc0012.c rtl-sdr/src/tuner_fc0013.c rtl-sdr/src/tuner_fc2580.c rtl-sdr/src/tuner_r82xx.c'
run mingw "
x86_64-w64-mingw32-gcc -O2 -shared -o out/corvus-rtl-$V-windows-x64.dll -Irtl-sdr/include -I/opt/libusb/include/libusb-1.0 -Drtlsdr_EXPORTS \
  $SRC /opt/libusb/lib/libusb-1.0.a -static-libgcc -Wl,-Bstatic -lwinpthread -Wl,-Bdynamic -Wl,--exclude-libs,ALL -Wl,--no-insert-timestamp -s
x86_64-w64-mingw32-windres -i driver/corvus-rtl-driver.rc -o /tmp/res.o
x86_64-w64-mingw32-gcc -O2 -Wall -Wno-unused -o out/corvus-rtl-driver-$V-windows-x64.exe -Idriver -Ilibwdi/libwdi -DDRIVER_VERSION='\"$DV\"' \
  driver/corvus-rtl-driver.c driver/wdi_glue.c libwdi/libwdi/pki.c libwdi/libwdi/logging.c /tmp/res.o \
  -lsetupapi -lnewdev -lcrypt32 -lole32 -static -Wl,--no-insert-timestamp -s"
run linux "
gcc -O2 -fPIC -fvisibility=hidden -shared -o out/libcorvus-rtl-$V-linux-x86_64.so -Wl,-soname,libcorvus-rtl.so -Irtl-sdr/include \$(pkg-config --cflags libusb-1.0) \
  -Drtlsdr_EXPORTS -DDETACH_KERNEL_DRIVER=1 $SRC \$(pkg-config --libs libusb-1.0) -lpthread -s"
(cd "$R/out" && sha256sum -- * | tee SHA256SUMS)
